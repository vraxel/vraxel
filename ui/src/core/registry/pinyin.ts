/** Pinyin声母 string for a label, e.g. "主机" -> "zj". Unmapped chars are dropped. */
export function pinyinInitials(s: string): string {
  let out = ""
  for (const ch of s) {
    const init = CHAR_INITIAL[ch]
    if (init) out += init
  }
  return out
}
